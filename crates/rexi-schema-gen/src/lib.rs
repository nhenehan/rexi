//! Builds grammar tables ahead of time, at build time instead of at run time (the
//! gSOAP-style path).
//!
//! [`render`] turns compiled grammar tables into Rust source code. The code declares
//! a `pub static <NAME>: GrammarSet<'static>`, laid out like the hand-written
//! `rexi_core::grammar::options_grammar`. It also declares a `pub const`
//! [`QNameId`] for every declared element and attribute name, so callers can match
//! events by number instead of comparing strings.
//!
//! ## Where this crate fits
//!
//! `rexi-schema` compiles XSD files into grammar tables; this crate writes those
//! tables out as Rust source. The program that includes the file then needs only
//! `rexi-core` (which works without `std`), not the schema compiler. The
//! `rexi-schema-gen` binary does it all from the command line:
//!
//! ```text
//! rexi-schema-gen order.xsd --out src/tables.rs --name ORDER_GRAMMARS
//! rexi-schema-gen order.xsd --out src/tables.rs --name ORDER_GRAMMARS --check
//! ```
//!
//! `--check` writes nothing and exits with 1 when the file is out of date, so a
//! test or CI step can catch tables that were not regenerated.
//!
//! [`QNameId`]: rexi_core::ids::QNameId

#![warn(missing_docs)]

use std::collections::BTreeSet;
use std::fmt::Write as _;

use rexi_core::datatype::{DatatypeKind, WhiteSpace};
use rexi_core::grammar::{GrammarSetBuf, GrammarTables, Span, Terminal};
use rexi_core::ids::{NONE, QNameId};

/// Rendering options.
#[derive(Debug, Clone)]
pub struct RenderOptions<'a> {
    /// Name of the generated `static`, for example `GRAMMARS`.
    pub name: &'a str,
    /// Path of the `rexi-core` crate, as seen from the generated module.
    pub core_path: &'a str,
    /// A line of any text, saying where the tables came from. It is written into
    /// the header comment.
    pub source: &'a str,
}

impl Default for RenderOptions<'_> {
    fn default() -> Self {
        Self {
            name: "GRAMMARS",
            core_path: "rexi_core",
            source: "",
        }
    }
}

/// Renders `tables` as a Rust module.
///
/// Each table becomes a private `static` slice named `<NAME>_<TABLE>` (such as
/// `GRAMMARS_RULES`). Then the public `<NAME>` static points at all of them. Index
/// values equal to `NONE` are written as `NONE`.
pub fn render(tables: &GrammarSetBuf, opts: &RenderOptions<'_>) -> String {
    let mut out = String::new();
    let o = &mut out;
    let name = opts.name;
    let p = |s: &str| format!("{name}_{s}");

    let _ = writeln!(o, "// @generated by rexi-schema-gen. Do not edit by hand.");
    if !opts.source.is_empty() {
        let _ = writeln!(o, "// Source: {}", opts.source);
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "#![allow(clippy::all, unused_imports)]");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "use {}::datatype::{{DatatypeKind, WhiteSpace}};",
        opts.core_path
    );
    let _ = writeln!(
        o,
        "use {}::grammar::{{ElementDecl, GlobalAttribute, Grammar, GrammarSet, Production, Rule, Span, Terminal, TypeDecl, UriEntry}};",
        opts.core_path
    );
    let _ = writeln!(o, "use {}::ids::{{NONE, QNameId}};", opts.core_path);
    let _ = writeln!(o, "use {}::value::DateTimeKind;", opts.core_path);
    let _ = writeln!(o);

    render_name_consts(o, tables);

    // Strings.
    let _ = writeln!(o, "static {}: &[&str] = &[", p("STRINGS"));
    for s in &tables.strings {
        let _ = writeln!(o, "    {s:?},");
    }
    let _ = writeln!(o, "];\n");

    let _ = writeln!(o, "static {}: &[UriEntry] = &[", p("URIS"));
    for u in &tables.uris {
        let _ = writeln!(
            o,
            "    UriEntry {{ uri: {}, prefixes: {}, local_names: {} }},",
            u.uri,
            span(u.prefixes),
            span(u.local_names)
        );
    }
    let _ = writeln!(o, "];\n");

    u32_slice(o, &p("PREFIXES"), &tables.prefixes);
    u32_slice(o, &p("LOCAL_NAMES"), &tables.local_names);

    let _ = writeln!(o, "static {}: &[Production] = &[", p("PRODUCTIONS"));
    for pr in &tables.productions {
        let _ = writeln!(
            o,
            "    Production::new({}, {}),",
            terminal(pr.terminal),
            idx(pr.next)
        );
    }
    let _ = writeln!(o, "];\n");

    let _ = writeln!(o, "static {}: &[Rule] = &[", p("RULES"));
    for r in &tables.rules {
        let _ = writeln!(o, "    Rule {{ productions: {} }},", span(r.productions));
    }
    let _ = writeln!(o, "];\n");

    let _ = writeln!(o, "static {}: &[Grammar] = &[", p("GRAMMARS"));
    for g in &tables.grammars {
        let _ = writeln!(o, "    Grammar {{ rules: {} }},", span(g.rules));
    }
    let _ = writeln!(o, "];\n");

    let _ = writeln!(o, "static {}: &[ElementDecl] = &[", p("ELEMENTS"));
    for e in &tables.elements {
        let _ = writeln!(
            o,
            "    ElementDecl {{ qname: {}, type_idx: {}, nillable: {}, global: {} }},",
            qname(e.qname),
            idx(e.type_idx),
            e.nillable,
            e.global
        );
    }
    let _ = writeln!(o, "];\n");

    u32_slice(o, &p("GLOBAL_ELEMENTS"), &tables.global_elements);

    let _ = writeln!(
        o,
        "static {}: &[GlobalAttribute] = &[",
        p("GLOBAL_ATTRIBUTES")
    );
    for a in &tables.global_attributes {
        let _ = writeln!(
            o,
            "    GlobalAttribute {{ qname: {}, type_idx: {} }},",
            qname(a.qname),
            idx(a.type_idx)
        );
    }
    let _ = writeln!(o, "];\n");

    let _ = writeln!(o, "static {}: &[TypeDecl] = &[", p("TYPES"));
    for t in &tables.types {
        let dt = match t.datatype {
            Some(d) => format!("Some({})", datatype(d)),
            None => "None".to_string(),
        };
        let _ = writeln!(
            o,
            "    TypeDecl {{ qname: {}, grammar: {}, empty_grammar: {}, datatype: {dt}, typecastable: {} }},",
            qname(t.qname),
            idx(t.grammar),
            idx(t.empty_grammar),
            t.typecastable
        );
    }
    let _ = writeln!(o, "];\n");

    let _ = writeln!(o, "static {}: &[Span] = &[", p("ENUM_SETS"));
    for s in &tables.enum_sets {
        let _ = writeln!(o, "    {},", span(*s));
    }
    let _ = writeln!(o, "];\n");

    u32_slice(o, &p("ENUM_VALUES"), &tables.enum_values);

    let schema_id = match &tables.schema_id {
        Some(s) => format!("Some({s:?})"),
        None => "None".to_string(),
    };
    let _ = writeln!(o, "pub static {name}: GrammarSet<'static> = GrammarSet {{");
    for (field, suffix) in [
        ("strings", "STRINGS"),
        ("uris", "URIS"),
        ("prefixes", "PREFIXES"),
        ("local_names", "LOCAL_NAMES"),
        ("productions", "PRODUCTIONS"),
        ("rules", "RULES"),
        ("grammars", "GRAMMARS"),
        ("elements", "ELEMENTS"),
        ("global_elements", "GLOBAL_ELEMENTS"),
        ("global_attributes", "GLOBAL_ATTRIBUTES"),
        ("types", "TYPES"),
        ("enum_sets", "ENUM_SETS"),
        ("enum_values", "ENUM_VALUES"),
    ] {
        let _ = writeln!(o, "    {field}: {},", p(suffix));
    }
    let _ = writeln!(o, "    schema_id: {schema_id},");
    let _ = writeln!(o, "}};");
    out
}

/// Writes `pub const LN_<NAME>: QNameId` for every declared element name and every
/// attribute name used in an `AT` production. When two names give the same
/// identifier, the later one gets `_<uri id>_<local id>` added to the end.
fn render_name_consts(o: &mut String, t: &GrammarSetBuf) {
    let mut qnames = BTreeSet::new();
    for e in &t.elements {
        qnames.insert(e.qname);
    }
    for p in &t.productions {
        if let Terminal::At(q, _) = p.terminal {
            qnames.insert(q);
        }
    }
    let mut used = BTreeSet::new();
    let mut lines = Vec::new();
    for q in qnames {
        let Some(local) = t.local_name_str(q) else {
            continue;
        };
        let mut ident = format!("LN_{}", screaming_snake(local));
        if !used.insert(ident.clone()) {
            ident = format!("{ident}_{}_{}", q.uri, q.local);
            used.insert(ident.clone());
        }
        let uri = t.uri_str(q.uri).unwrap_or("");
        lines.push(format!(
            "/// `{{{uri}}}{local}`\npub const {ident}: QNameId = {};",
            qname(q)
        ));
    }
    for l in lines {
        let _ = writeln!(o, "{l}");
    }
    if !t.elements.is_empty() {
        let _ = writeln!(o);
    }
}

/// Turns a name into SCREAMING_SNAKE_CASE: `orderId` → `ORDER_ID`, `pre-compress` →
/// `PRE_COMPRESS`. Each run of characters that are not ASCII letters or digits
/// becomes one `_`. A leading `_` is added if the result is empty or starts with a
/// digit, so it is a valid identifier.
pub fn screaming_snake(s: &str) -> String {
    let mut out = String::new();
    let mut prev_lower = false;
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            if c.is_ascii_uppercase() && prev_lower {
                out.push('_');
            }
            prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
            out.push(c.to_ascii_uppercase());
        } else {
            if !out.ends_with('_') {
                out.push('_');
            }
            prev_lower = false;
        }
    }
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// Writes a `static <name>: &[u32]`, 16 values per line.
fn u32_slice(o: &mut String, name: &str, v: &[u32]) {
    let _ = writeln!(o, "static {name}: &[u32] = &[");
    for chunk in v.chunks(16) {
        let items: Vec<String> = chunk.iter().map(|x| idx(*x)).collect();
        let _ = writeln!(o, "    {},", items.join(", "));
    }
    let _ = writeln!(o, "];\n");
}

/// An index as Rust source: `NONE` for the "no index" marker value, else the
/// number.
fn idx(i: u32) -> String {
    if i == NONE {
        "NONE".to_string()
    } else {
        i.to_string()
    }
}

fn span(s: Span) -> String {
    format!("Span::new({}, {})", s.start, s.len)
}

fn qname(q: QNameId) -> String {
    format!("QNameId::new({}, {})", idx(q.uri), idx(q.local))
}

fn terminal(t: Terminal) -> String {
    match t {
        Terminal::Se(e) => format!("Terminal::Se({})", idx(e)),
        Terminal::SeNs(u) => format!("Terminal::SeNs({})", idx(u)),
        Terminal::At(q, ty) => format!("Terminal::At({}, {})", qname(q), idx(ty)),
        Terminal::AtNs(u) => format!("Terminal::AtNs({})", idx(u)),
        Terminal::Ch(ty) => format!("Terminal::Ch({})", idx(ty)),
        // Variants with no fields: their Debug text is the variant name.
        other => format!("Terminal::{other:?}"),
    }
}

fn datatype(d: DatatypeKind) -> String {
    match d {
        DatatypeKind::String { whitespace } => {
            format!("DatatypeKind::String {{ whitespace: {} }}", ws(whitespace))
        }
        DatatypeKind::RestrictedString { whitespace } => format!(
            "DatatypeKind::RestrictedString {{ whitespace: {} }}",
            ws(whitespace)
        ),
        DatatypeKind::NBit { min, bits } => {
            format!("DatatypeKind::NBit {{ min: {min}, bits: {bits} }}")
        }
        DatatypeKind::DateTime(k) => format!("DatatypeKind::DateTime(DateTimeKind::{k:?})"),
        DatatypeKind::Enumeration { set, item } => format!(
            "DatatypeKind::Enumeration {{ set: {}, item: {} }}",
            idx(set),
            idx(item)
        ),
        DatatypeKind::List { item } => format!("DatatypeKind::List {{ item: {} }}", idx(item)),
        DatatypeKind::Boolean
        | DatatypeKind::BooleanPattern
        | DatatypeKind::Integer
        | DatatypeKind::UnsignedInteger
        | DatatypeKind::Decimal
        | DatatypeKind::Float
        | DatatypeKind::Base64Binary
        | DatatypeKind::HexBinary
        | DatatypeKind::QName
        | DatatypeKind::Untyped => format!("DatatypeKind::{d:?}"),
        // A kind added to rexi-core later.
        other => format!("DatatypeKind::{other:?}"),
    }
}

fn ws(w: WhiteSpace) -> String {
    format!("WhiteSpace::{w:?}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn screaming_snake_names() {
        assert_eq!(screaming_snake("orderId"), "ORDER_ID");
        assert_eq!(screaming_snake("pre-compress"), "PRE_COMPRESS");
        assert_eq!(screaming_snake("header"), "HEADER");
        assert_eq!(screaming_snake("ID"), "ID");
        assert_eq!(screaming_snake("item2Name"), "ITEM2_NAME");
        assert_eq!(screaming_snake("1st"), "_1ST");
    }
}
